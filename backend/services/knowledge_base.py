def search_knowledge(query: str, category: str = "all") -> list[dict]:
    """搜索金融知识库"""
    query_lower = query.lower()
    results = []
    for item in KNOWLEDGE_BASE:
        # 匹配词条名称或别名
        all_names = [item["term"].lower()] + [a.lower() for a in item.get("alias", [])]
        if any(q in " ".join(all_names) or any(q in a for a in all_names) for q in query_lower.split()):
            results.append(item)
            continue
        # 匹配内容
        if query_lower in item["what"].lower() or query_lower in item["why_matters"].lower():
            results.append(item)

    if category != "all":
        results = [r for r in results if r["category"] == category]

    return results


def list_all_terms() -> list[dict]:
    """列出所有词条（简化版）"""
    return [{"id": t["id"], "term": t["term"], "alias": t["alias"], "category": t["category"]} for t in KNOWLEDGE_BASE]


def get_term(term_id: int) -> dict | None:
    """获取单个词条详情"""
    for item in KNOWLEDGE_BASE:
        if item["id"] == term_id:
            return item
    return None


def get_terms_by_category(category: str) -> list[dict]:
    """按分类获取词条"""
    return [t for t in KNOWLEDGE_BASE if t["category"] == category]
